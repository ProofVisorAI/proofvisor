#!/usr/bin/env python3
"""Check local documentation links and source/documentation coverage, without network access.

This checks structure and inventory, not the truth of prose or runtime behavior.
Run the Rust documentation tests and rustdoc as well when source interfaces change.
"""
from __future__ import annotations

import html
from html.parser import HTMLParser
from pathlib import Path
import re
import subprocess
import sys
import tomllib
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]


class Page(HTMLParser):
    def __init__(self, text: str):
        super().__init__()
        self.links: list[str] = []
        self.anchors: set[str] = set()
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        for name, value in attrs:
            if value is None:
                continue
            if name == 'id' or (tag == 'a' and name == 'name'):
                self.anchors.add(value)
            if name in ('href', 'src'):
                self.links.append(value)


def prose(text: str) -> str:
    return re.sub(r'^(`{3,}|~{3,}).*?^\1\s*$', '', text, flags=re.M | re.S)


def anchors(path: Path) -> set[str]:
    text = path.read_text()
    found = Page(text).anchors
    if path.suffix == '.md':
        used: dict[str, int] = {}
        for heading in re.findall(r'^#{1,6}\s+(.+?)\s*#*$', prose(text), re.M):
            heading = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', heading)
            heading = re.sub(r'<[^>]*>', '', heading)
            slug = re.sub(r'[^\w\- ]', '', html.unescape(heading).lower()).replace(' ', '-')
            count = used.get(slug, 0)
            used[slug] = count + 1
            found.add(slug + (f'-{count}' if count else ''))
        found.add('readme')  # GitHub's README view anchor.
    return found


def link_target(source: Path, link: str):
    parsed = urlsplit(html.unescape(link.strip('<>')))
    path = unquote(parsed.path)
    if parsed.netloc == 'proofvisor.com':
        return ROOT / 'docs' / path.lstrip('/'), unquote(parsed.fragment)
    if parsed.netloc == 'github.com':
        match = re.match(r'/ProofVisorAI/proofvisor/(?:blob|tree)/main/(.*)', path)
        if match:
            return ROOT / match[1], unquote(parsed.fragment)
        return None
    if parsed.scheme or parsed.netloc:
        return None
    if path.startswith('/'):
        if source.is_relative_to(ROOT / 'crates/pv-harness/dashboard'):
            if path.startswith('/dashboard/'):
                return source.parent / path.removeprefix('/dashboard/'), unquote(parsed.fragment)
            routes = (ROOT / 'crates/pv-harness/src/routes.rs').read_text()
            if f'.route("{path}"' in routes:
                return None  # A daemon handler, not a static website file.
        return ROOT / 'docs' / path.lstrip('/'), unquote(parsed.fragment)
    return source.parent / path if path else source, unquote(parsed.fragment)


def main() -> int:
    names = subprocess.check_output(['git', 'ls-files', '--cached', '--others', '--exclude-standard'], cwd=ROOT, text=True).splitlines()
    files = sorted({ROOT / p for p in names if p.endswith(('.md', '.html')) and (ROOT / p).is_file()})
    errors = []
    checked = 0
    anchor_cache = {}
    for source in files:
        text = source.read_text()
        if source.suffix == '.md':
            text = prose(text)
        links = Page(text).links
        if source.suffix == '.md':
            links += re.findall(r'!?\[[^\]]*\]\(<?([^\s)>]+)>?(?:\s+"[^"]*")?\)', text)
        if source.suffix == '.md':
            links += re.findall(r'<(https?://[^>]+)>', text)
            links += re.findall(r'^\s*\[(?!\^)[^\]]+\]:\s*<?([^\s>]+)', text, re.M)
        for link in links:
            resolved = link_target(source, link)
            if resolved is None:
                continue
            target, fragment = resolved
            target = target.resolve()
            # Rustdoc is generated by pages.yml; it does not live in docs/.
            if target.is_relative_to(ROOT / 'docs/api'):
                continue
            checked += 1
            label = f'{source.relative_to(ROOT)}: {link}'
            if not target.exists():
                errors.append(f'Missing target: {label}')
                continue
            if target.is_dir():
                target = next((target / name for name in ('index.html', 'README.md') if (target / name).exists()), target)
            if fragment and target.is_file() and target.suffix in ('.md', '.html'):
                if re.fullmatch(r'L\d+(?:-L\d+)?', fragment):
                    continue
                if target not in anchor_cache:
                    anchor_cache[target] = anchors(target)
                if fragment not in anchor_cache[target]:
                    errors.append(f'Missing anchor: {label}')

    manifest = tomllib.loads((ROOT / 'Cargo.toml').read_text())
    architecture = (ROOT / 'ARCHITECTURE.md').read_text()
    crates = manifest['workspace']['members']
    for member in crates:
        name = Path(member).name
        if f'`{name}`' not in architecture:
            errors.append(f'ARCHITECTURE.md omits workspace crate {name}')
    homepage = (ROOT / 'docs/index.html').read_text()
    if f'workspace of {len(crates)} crates' not in homepage:
        errors.append(f'The homepage crate count must match the {len(crates)} workspace members')

    cli = (ROOT / 'crates/pv-cli/src/main.rs').read_text().split('enum Command {', 1)[1].split('\n}', 1)[0]
    variants = re.findall(r'^    ([A-Z]\w+)(?: \{|,)', cli, re.M)
    commands = [re.sub(r'(?<!^)(?=[A-Z])', '-', v).lower() for v in variants]
    features = (ROOT / 'docs/FEATURES.md').read_text().split('## 4.', 1)[1].split('\n## ', 1)[0]
    for command in commands:
        if f'`{command}`' not in features:
            errors.append(f'FEATURES.md CLI inventory omits {command}')
    count = re.search(r'The CLI has (\d+) subcommands', features)
    if count is None or int(count[1]) != len(commands):
        errors.append(f'FEATURES.md CLI count must match the {len(commands)} source commands')

    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    print(f'Checked {len(files)} documents, {checked} local links, {len(crates)} crates and {len(commands)} CLI commands.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
